"""Markdown reporter — for PR comments and documentation."""

from __future__ import annotations

from ..models import ScanResult, Severity


def _severity_badge(severity: Severity) -> str:
    badges = {
        Severity.CRITICAL: "🔴 CRITICAL",
        Severity.HIGH: "🟠 HIGH",
        Severity.MEDIUM: "🟡 MEDIUM",
        Severity.LOW: "🔵 LOW",
        Severity.INFO: "⚪ INFO",
    }
    return badges.get(severity, severity.value)


def render_markdown(result: ScanResult) -> str:
    """Render scan results as a Markdown document."""
    lines: list[str] = []

    # Header
    lines.append("# AI Code Security Scanner — Scan Report\n")
    lines.append(f"**Scanner version:** {result.scanner_version}\n")
    lines.append(f"**Project:** `{result.project_path}`\n")
    lines.append(f"**Scan time:** {result.scan_time}\n")
    lines.append(f"**Duration:** {result.duration_seconds:.3f}s\n")
    lines.append(f"**Files scanned:** {result.files_scanned}\n")
    lines.append("\n---\n")

    # Summary
    lines.append("## Summary\n")
    lines.append(f"| Severity | Count |")
    lines.append(f"|----------|-------|")
    lines.append(f"| {Severity.CRITICAL.value} | {result.critical_count} |")
    lines.append(f"| {Severity.HIGH.value} | {result.high_count} |")
    lines.append(f"| {Severity.MEDIUM.value} | {result.medium_count} |")
    lines.append(f"| {Severity.LOW.value} | {result.low_count} |")
    lines.append(f"| {Severity.INFO.value} | {result.info_count} |")
    lines.append(f"| **Total** | **{len(result.active_findings)}** |")

    if result.suppressed_count > 0:
        lines.append(f"\n_Suppressed: {result.suppressed_count}_\n")

    lines.append("\n---\n")

    # Findings
    if result.active_findings:
        lines.append("## Findings\n")
        for idx, finding in enumerate(result.active_findings, 1):
            lines.append(f"### {idx}. {_severity_badge(finding.severity)} — {finding.title}\n")
            lines.append(f"**Rule:** `{finding.rule_id}` | **File:** `{finding.file}:{finding.line}` | **Language:** `{finding.language.value}`\n")
            lines.append(f"**Confidence:** {finding.confidence.value} | **Manual verification:** {'Required' if finding.manual_verification_required else 'Not required'}\n")
            lines.append(f"\n**Description:**\n{finding.description}\n")
            lines.append(f"\n**Evidence:**\n```\n{finding.evidence}\n```\n")
            lines.append(f"\n**Impact:**\n{finding.impact}\n")
            lines.append(f"\n**Remediation:**\n{finding.remediation}\n")
            if finding.references:
                lines.append("\n**References:**\n")
                for ref in finding.references:
                    lines.append(f"- [{ref}]({ref})")
            lines.append("\n---\n")
    else:
        lines.append("## Findings\n\nNo security findings detected.\n")

    # Footer
    lines.append("\n---\n")
    lines.append("## About This Report\n")
    lines.append("This report was generated by the **AI Code Security Scanner**.\n")
    lines.append("The scanner uses pattern-based static analysis to identify common security "
                 "weaknesses in Python and JavaScript code.\n")
    lines.append("\n> **Note:** A clean scan does **not** prove that the code is secure. "
                 "Pattern-based detection can produce false positives and may miss "
                 "vulnerabilities not covered by its rule set. Manual verification and "
                 "additional testing are recommended.\n")
    lines.append(f"\n_Generated at {result.scan_time}_\n")

    return "\n".join(lines)
